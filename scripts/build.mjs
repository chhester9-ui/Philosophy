// Builds the app's content bundle: copies lesson JSON into app/content,
// writes app/content/index.json (course map + glossary) and app/sw.js (offline cache list).
// Usage: node scripts/build.mjs
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const app = join(root, 'app');
const out = join(app, 'content');
const syllabus = JSON.parse(readFileSync(join(root, 'content/syllabus.json'), 'utf8'));

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'lessons'), { recursive: true });
mkdirSync(join(out, 'tracks'), { recursive: true });

const glossary = [];
const load = (dir, id) => {
  const p = join(root, 'content', dir, `${id}.json`);
  if (!existsSync(p)) return null;
  const L = JSON.parse(readFileSync(p, 'utf8'));
  writeFileSync(join(out, dir, `${id}.json`), JSON.stringify(L));
  for (const v of L.vocabulary || []) glossary.push({ term: v.term, definition: v.definition, example: v.example, lessonId: id });
  return L;
};

const units = syllabus.units.map(u => ({
  id: u.id, title: u.title,
  days: u.days.map(d => {
    const id = `day-${String(d.day).padStart(2, '0')}`;
    const L = load('lessons', id);
    return { id, day: d.day, audio: existsSync(join(app, 'audio', `${id}.json`)), title: L?.title || d.title, subtitle: L?.subtitle || '', minutes: L?.estimatedMinutes || 45,
      era: L?.era || '', philosophers: L?.philosophers || [], review: /^Review:|Final Synthesis/.test(d.title), available: !!L };
  }),
}));
const tracks = syllabus.tracks.map(t => ({
  id: t.id, title: t.title, description: t.description, recommendedAfterDay: t.recommendedAfterDay,
  lessons: t.lessons.map(l => {
    const id = `${t.id}-${l.order}`;
    const L = load('tracks', id);
    return { id, order: l.order, audio: existsSync(join(app, 'audio', `${id}.json`)), title: L?.title || l.title, subtitle: L?.subtitle || '', minutes: L?.estimatedMinutes || 45, available: !!L };
  }),
}));

writeFileSync(join(out, 'index.json'), JSON.stringify({ title: syllabus.title, units, tracks, glossary }));

// Service worker with a precache list and a content-hash version.
const files = [];
const walk = d => readdirSync(d).forEach(f => {
  const p = join(d, f);
  if (statSync(p).isDirectory()) walk(p);
  else if (f !== 'sw.js' && !f.startsWith('.')) files.push(relative(app, p).split('\\').join('/'));
});
walk(app);
files.sort();
// Narration audio is streamed on demand, not precached (it is hundreds of MB).
// Its timing files still count toward the version so an updated recording refreshes the app.
const precache = files.filter(f => !f.startsWith('audio/'));
const hash = createHash('sha256');
precache.forEach(f => hash.update(f).update(readFileSync(join(app, f))));
files.filter(f => f.startsWith('audio/') && f.endsWith('.json')).forEach(f => hash.update(f).update(readFileSync(join(app, f))));
const version = hash.digest('hex').slice(0, 12);
const sw = `// Generated by scripts/build.mjs. Do not edit by hand.
const CACHE = 'phil90-${version}';
const FILES = ${JSON.stringify(['./', ...precache])};
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return;     // e.g. the tutor's calls to Google
  if (url.pathname.includes('/audio/')) return;   // stream narration straight from the network
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(hit => hit || fetch(e.request)));
});
`;
writeFileSync(join(app, 'sw.js'), sw);

const avail = units.flatMap(u => u.days).filter(d => d.available).length;
const tAvail = tracks.flatMap(t => t.lessons).filter(l => l.available).length;
const narrated = [...units.flatMap(u => u.days), ...tracks.flatMap(t => t.lessons)].filter(l => l.audio).length;
console.log(`Built: ${avail}/90 daily lessons, ${tAvail}/30 track lessons, ${narrated} narrated, ${glossary.length} glossary terms, ${precache.length} cached files (v${version}).`);
